/** Keys present for a language (used by the dictionary parity test). */
export function dictionaryKeys(lang: Lang): string[] {
  return Object.entries(D).filter(([, v]) => typeof v[lang] === 'string' && v[lang].trim().length > 0).map(([k]) => k);
}

@Injectable({ providedIn: 'root' })
export class I18n {
  readonly lang = signal<Lang>('ar');
  readonly dir = computed(() => (this.lang() === 'ar' ? 'rtl' : 'ltr'));
  constructor() {
    effect(() => {
      const d = document.documentElement;
      d.lang = this.lang();
      d.dir = this.dir();
    });
  }
  t(key: string): string { const e = D[key]; return e ? e[this.lang()] : key; }
  toggle() { this.lang.update((l) => (l === 'ar' ? 'en' : 'ar')); }
  fmt(iso: string | null | undefined): string {
    if (!iso) return '-';
    const d = new Date(iso);
    return isNaN(d.getTime()) ? '-' : d.toLocaleString(this.lang() === 'ar' ? 'ar-EG-u-nu-latn' : 'en-GB', { dateStyle: 'medium', timeStyle: 'short' });
  }
}
